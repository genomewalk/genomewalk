test("unsupported DNA headers distinguish provider and layout without retaining private text", async () => {
  const privateText = "SYNTHETIC_PRIVATE_HEADER_AND_FILENAME";
  const genotypeColumns = "rsid\tchromosome\tposition\tgenotype";
  const alleleColumns = "rsid\tchromosome\tposition\tallele1\tallele2";
  const cases = [
    ["", genotypeColumns, "unrecognized", "genotype", "provider-unrecognized"],
    [`# ${privateText}\n`, alleleColumns, "unrecognized", "allele-pair", "provider-unrecognized"],
    ["# 23andMe\n", alleleColumns, "23andMe", "allele-pair", "columns-mismatch"],
    ["# AncestryDNA\n", genotypeColumns, "AncestryDNA", "genotype", "columns-mismatch"],
    [
      "# 23andMe\n",
      `rsid\tchromosome\tposition\t${privateText}`,
      "23andMe",
      "other",
      "columns-mismatch",
    ],
  ] as const;
  for (const [meta, columns, provider, layout, reason] of cases) {
    await assert.rejects(
      openConsumerFile(file(`${meta}# ${columns}\n${row(100, "CT")}`, `${privateText}.txt`)),
      (error: unknown) => {
        assert.ok(error instanceof AppError);
        assert.equal(error.code, "DNA_FORMAT_UNSUPPORTED");
        assert.deepEqual(error.details, {
          formatReason: reason,
          headerProvider: provider,
          headerLayout: layout,
        });
        assert.match(
          error.message,
          reason === "provider-unrecognized"
            ? /identify a supported provider/
            : /columns don’t match/,
        );
        assert.equal(error.message.includes(privateText), false);
        assert.equal(JSON.stringify(error).includes(privateText), false);
        return true;
      },
    );
  }
});


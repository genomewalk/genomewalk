const text = (rows: string[], extra = "") =>
  `# This data file is generated by 23andMe.\n# reference assembly build 37; plus strand\n${extra}# rsid\tchromosome\tposition\tgenotype\n${rows.join("\n")}`;
const file = (content: BlobPart, name = "synthetic.txt") => new File([content], name);
const row = (pos: number, gt: string, chrom = "1") => `rs${pos}\t${chrom}\t${pos}\t${gt}`;
const entry = (pos: number, ref = "C", alt = "T") =>
  `1\t${pos}\t${ref}\t${alt}\tP\t2\tEXAMPLE\tIllustrative condition\t.\t\t.\t.\t123\t\tPathogenic`;
const catalog = (...positions: number[]) =>
  new Map(positions.map((pos) => [`1:${pos}:C:T`, entry(pos)]));


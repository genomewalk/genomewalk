test("truncated ZIP directories and corrupted archive checksums are rejected", async () => {
  const bytes = strToU8(text([row(100, "CT")]));
  const zip = zipSync({ "synthetic.txt": bytes });
  await assert.rejects(openConsumerFile(file(zip.slice(0, -10), "truncated.zip")), /incomplete/);
  const gzip = gzipSync(bytes);
  gzip[gzip.length - 8]! ^= 1;
  await assert.rejects(openConsumerFile(file(gzip, "corrupt.gz")), /integrity/);
  // Alter the declared CRC while leaving a valid compressed stream.
  const zipBad = zipSync({ "synthetic.txt": bytes });
  for (let i = 0; i < zipBad.length - 4; i++)
    if (zipBad[i] === 80 && zipBad[i + 1] === 75 && zipBad[i + 2] === 1 && zipBad[i + 3] === 2) {
      zipBad[i + 16]! ^= 1;
      break;
    }
  await assert.rejects(openConsumerFile(file(zipBad, "corrupt.zip")), /integrity/);
});


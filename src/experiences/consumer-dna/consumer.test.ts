test("opening archives reports byte progress, while a header-only text read does not", async () => {
  const content = text(Array.from({ length: 25000 }, (_, i) => row(100 + i, "CT")));
  for (const archive of [
    file(zipSync({ "synthetic.txt": strToU8(content) }), "synthetic.zip"),
    file(gzipSync(strToU8(content)), "synthetic.gz"),
  ]) {
    const values: number[] = [];
    await openConsumerFile(archive, undefined, (fraction) => values.push(fraction));
    assert.equal(values[0], 0);
    assert.equal(values.at(-1), 1);
    assert.ok(values.some((fraction) => fraction > 0 && fraction < 1));
    assert.ok(
      values.every(
        (fraction, i) => fraction >= 0 && fraction <= 1 && (!i || fraction >= values[i - 1]!),
      ),
    );
  }
  const values: number[] = [];
  await openConsumerFile(file(content), undefined, (fraction) => values.push(fraction));
  assert.deepEqual(values, []);
});

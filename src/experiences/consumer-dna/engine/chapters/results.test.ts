test("results forward file progress to the loader and reuse completed matches", async (t) => {
  const previousDocument = globalThis.document;
  const previousCatalog = ctx.catalog;
  globalThis.document = testDocument();
  t.after(() => {
    globalThis.document = previousDocument;
    selectSource(null);
    ctx.catalog = previousCatalog;
  });
  let reads = 0;
  let downloads = 0;
  const sourceHash = "1".repeat(64);
  t.mock.method(globalThis, "fetch", async (url: string | URL | Request) => {
    assert.equal(url, "/ref/consumer-dna/GRCh37/rsids.json.gz");
    downloads++;
    return new Response(
      gzipSync(
        new TextEncoder().encode(
          JSON.stringify({
            schema: 1,
            build: "GRCh37",
            sources: { catalog: { sha256: sourceHash } },
            catalog: {},
            markers: {},
            aliases: {},
          }),
        ),
      ),
    );
  });
  selectSource(
    partialFixture({
      build: "GRCh37",
      format: "consumer",
      label: "23andMe",
      header: {},
      capabilities: { matching: true },
      async readCalls(_each: unknown, progress: (fraction: number) => void) {
        reads++;
        progress(0.13);
        progress(1);
      },
    }),
  );
  ctx.catalog = partialFixture({
    build: "GRCh37",
    source: { sha256: sourceHash },
    async *rows(_signal: AbortSignal, progress: (fraction: number) => void) {
      progress(1);
      yield* [];
    },
  });
  const values: number[] = [];
  const options: ChapterOptions = { onProgress: (fraction) => values.push(fraction) };
  const out = testElement("div");
  await results.run(out, options);
  assert.deepEqual(values, [0, 0.2, 0.278, 0.8, 1]);
  assert.ok(out.children.every((child) => child.className !== "prog"));
  await results.run(testElement("div"), options);
  assert.equal(reads, 1);
  assert.equal(downloads, 1);
  assert.equal("lookup" in ctx.catalog!, false);
  assert.deepEqual(values, [0, 0.2, 0.278, 0.8, 1]);
});

// Minimal interactive elements let the real list renderer append its cards.
function listDocument() {
  const doc = mockDocument();
  const base = doc.createElement.bind(doc);
  doc.createElement = partialFixture((tag: string) => {
    const element = base(tag) as TestElement;
    const selected = new Map<string, TestElement>();
    Object.assign(element, {
      value: "",
      addEventListener() {},
      querySelector(selector: string) {
        if (!selected.has(selector)) {
          const child = partialFixture<TestElement>(doc.createElement("div"));
          selected.set(selector, child);
        }
        return selected.get(selector);
      },
      querySelectorAll: () => [],
      setAttribute() {},
      replaceChildren(...children: TestElement[]) {
        element.children.splice(0);
        element.append(...children);
      },
    });
    element.classList.add = (...names: string[]) => {
      element.className += " " + names.join(" ");
    };
    return element;
  });
  return doc;
}

async function renderCachedResults(t: TestContext, rows: string[]) {
  const originalDocument = globalThis.document;
  const originalCatalog = ctx.catalog;
  globalThis.document = listDocument();
  t.after(() => {
    globalThis.document = originalDocument;
    selectSource(null);
    ctx.catalog = originalCatalog;
  });
  const source = await openConsumerFile(
    new File(
      [
        `# This data file is generated by 23andMe.\n# reference assembly build 37; plus strand\n# rsid\tchromosome\tposition\tgenotype\n${rows.join("\n")}`,
      ],
      "synthetic.txt",
    ),
  );
  selectSource(source);
  ctx.catalog = partialFixture({ build: "GRCh37" });
  const catalogue = new Map(
    [
      [100, "T"],
      [100, "G"],
      [200, "T"],
    ].map(([pos, alt]) => [
      `1:${pos}:C:${alt}`,
      `1\t${pos}\tC\t${alt}\tP\t2\tEXAMPLE\tIllustrative condition\t.\t\t.\t.\t123\t\tPathogenic`,
    ]),
  );
  ctx.matches = await findMatches(source, catalogue);
  const out = testElement("div");
  assert.equal(await results.run(out), true);
  const html = out.children.map((child) => child.innerHTML).join("\n");
  const list = out.children.find((child) => child.className === "mlist");
  assert.ok(list, "verification-only records must still render the shared list");
  const cards = [...list.querySelector<TestElement>(".ml-rows")!.children].filter(
    (child) => child.tagName === "details",
  );
  return { html, cards };
}

test("conflicting-only consumer results show raw verification records with zero summary counts", async (t) => {
  const { html, cards } = await renderCachedResults(t, ["rs100\t1\t100\tCT", "rs100\t1\t100\tCG"]);
  assert.match(html, /1 site was separated for verification/);
  assert.equal([...html.matchAll(/class="tv">0</g)].length, 3);
  assert.match(html, /Rows and sites in chapter 3/);
  assert.doesNotMatch(html, /No unambiguous supported allele remains/);
  assert.match(html, /Explore 0 results and 2 records needing verification/);
  assert.equal(cards.length, 2);
  for (const card of cards) {
    assert.match(card.innerHTML, /Needs verification/);
    assert.match(card.innerHTML, /rs100\s+1\s+100\s+CT/);
    assert.match(card.innerHTML, /rs100\s+1\s+100\s+CG/);
    assert.doesNotMatch(
      card.innerHTML,
      /EXAMPLE|Illustrative condition|Pathogenic|ClinVar|stars|mh-z/,
    );
  }
  assert.equal(ctx.matches!.length, 2, "raw observations remain available for inspection");
});

test("mixed consumer results count only unambiguous matches and place verification records separately", async (t) => {
  const { html, cards } = await renderCachedResults(t, [
    "rs100\t1\t100\tCT",
    "rs100\t1\t100\tCG",
    "rs200\t1\t200\tCT",
  ]);
  assert.match(html, /Explore 1 result and 2 records needing verification/);
  assert.equal([...html.matchAll(/class="tv">1</g)].length, 2, "one variant and one gene");
  assert.equal([...html.matchAll(/class="tv">0</g)].length, 1, "no publication references");
  assert.equal(cards.length, 3);
  assert.match(cards[0]!.innerHTML, /chr1:200/);
  assert.match(cards[0]!.innerHTML, /Pathogenic/);
  for (const card of cards.slice(1)) {
    assert.match(card.innerHTML, /Needs verification/);
    assert.doesNotMatch(
      card.innerHTML,
      /EXAMPLE|Illustrative condition|Pathogenic|ClinVar|stars|mh-z/,
    );
  }
});
